export default function sitemap(): MetadataRoute.Sitemap {
  const locales = ["en"];
  const entries: MetadataRoute.Sitemap = [];
  const buildDate = new Date("2026-09-23");

  for (const locale of locales) {
    for (const page of staticPages) {
      const depth = page.split("/").filter(Boolean).length;
      let priority = 0.7;
      if (page === "") priority = 1;
      else if (depth === 1) priority = 0.9;
      else if (depth === 2) priority = 0.8;
      else priority = 0.7;

      entries.push({
        url: `${BASE_URL}/${locale}${page}`,
        lastModified: buildDate,
        changeFrequency: page === "" || page === "/blog" ? "weekly" : "monthly",
        priority,
      });
    }

    const blogPosts = getAllPublishedSlugsWithDates();
    for (const post of blogPosts) {
      entries.push({
        url: `${BASE_URL}/${locale}/blog/${post.slug}`,
        lastModified: new Date(post.updated_at || post.published_at || Date.now()),
        changeFrequency: "monthly",
        priority: 0.6,
      });
    }

    const totalBlogPages = Math.ceil(blogPosts.length / 30);
    for (let p = 2; p <= totalBlogPages; p++) {
      entries.push({
        url: `${BASE_URL}/${locale}/blog/page/${p}`,
        lastModified: new Date(),
        changeFrequency: "weekly",
        priority: 0.5,
      });
    }

    const blogCategories = getAllCategories();
    for (const cat of blogCategories) {
      const slug = cat.toLowerCase().replace(/\s+/g, "-").replace(/&/g, "and");
      entries.push({
        url: `${BASE_URL}/${locale}/blog/category/${slug}`,
        lastModified: new Date(),
        changeFrequency: "weekly",
        priority: 0.7,
      });
    }
  }

  return entries;
}
